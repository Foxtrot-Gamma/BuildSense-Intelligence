def validate_relationships(activities, reviewed_data=None):
    """
    Validate activity relationships before schedule calculation.

    Checks:
    1. All predecessors exist.
    2. No activity is its own predecessor.
    3. Relationship type is valid.
    4. No-predecessor activities have no predecessor.
    5. Relationships requiring a predecessor have one.
    6. No circular dependencies.
    7. No unresolved AI review items remain.
    """

    errors = []

    if activities is None or activities.empty:
        errors.append(
            "No activities are available for validation."
        )
        return False, errors

    # ------------------------------------------------------
    # Check AI review status
    # ------------------------------------------------------

    if reviewed_data is not None and not reviewed_data.empty:

        if "Status" in reviewed_data.columns:

            pending_rows = reviewed_data[
                reviewed_data["Status"].astype(str).str.strip()
                == "⏳ Pending"
            ]

            if not pending_rows.empty:

                for _, row in pending_rows.iterrows():

                    errors.append(
                        f"{row['ID']}: Relationship review "
                        "is still pending."
                    )

    # ------------------------------------------------------
    # Build Activity ID lookup
    # ------------------------------------------------------

    activity_ids = set()

    for _, row in activities.iterrows():

        activity_id = str(
            row["ID"]
        ).strip()

        if activity_id:
            activity_ids.add(activity_id)

    # ------------------------------------------------------
    # Validate each relationship
    # ------------------------------------------------------

    graph = {}

    for _, row in activities.iterrows():

        activity_id = str(
            row["ID"]
        ).strip()

        predecessor = str(
            row["Predecessor"]
        ).strip()

        relationship = str(
            row["Relationship"]
        ).strip()

        graph[activity_id] = predecessor

        # ----------------------------------------------
        # Relationship type
        # ----------------------------------------------

        if relationship not in RELATIONSHIP_OPTIONS:

            errors.append(
                f"{activity_id}: Invalid relationship "
                f"'{relationship}'."
            )

        # ----------------------------------------------
        # No predecessor
        # ----------------------------------------------

        if relationship == "No Predecessor":

            if predecessor and predecessor.lower() not in [
                "none",
                "none 🔍"
            ]:

                errors.append(
                    f"{activity_id}: Relationship is "
                    "'No Predecessor' but a predecessor "
                    f"'{predecessor}' is assigned."
                )

            continue

        # ----------------------------------------------
        # Relationship requires predecessor
        # ----------------------------------------------

        if not predecessor or predecessor.lower() in [
            "none",
            "none 🔍"
        ]:

            errors.append(
                f"{activity_id}: Relationship "
                f"'{relationship}' requires a predecessor."
            )

            continue

        # ----------------------------------------------
        # Self predecessor
        # ----------------------------------------------

        if predecessor == activity_id:

            errors.append(
                f"{activity_id}: Activity cannot be "
                "its own predecessor."
            )

            continue

        # ----------------------------------------------
        # Predecessor exists
        # ----------------------------------------------

        if predecessor not in activity_ids:

            errors.append(
                f"{activity_id}: Predecessor "
                f"'{predecessor}' does not exist."
            )

    # ------------------------------------------------------
    # Detect circular dependencies
    # ------------------------------------------------------

    visited = set()
    active_path = set()

    def visit(activity_id, path):

        if activity_id in active_path:

            cycle_start = path.index(activity_id)

            cycle = (
                path[cycle_start:]
                + [activity_id]
            )

            errors.append(
                "Circular dependency detected: "
                + " → ".join(cycle)
            )

            return

        if activity_id in visited:
            return

        visited.add(activity_id)
        active_path.add(activity_id)

        predecessor = graph.get(activity_id)

        if (
            predecessor
            and predecessor in graph
        ):

            visit(
                predecessor,
                path + [predecessor]
            )

        active_path.remove(activity_id)

    for activity_id in graph:

        if activity_id not in visited:

            visit(
                activity_id,
                [activity_id]
            )

    # ------------------------------------------------------
    # Remove duplicate error messages
    # ------------------------------------------------------

    errors = list(dict.fromkeys(errors))

    if errors:
        return False, errors

    return True, []

