def process_ai_editor_change():
    widget_key = (
        "ai_relationship_editor_widget_"
        + str(st.session_state.get("ai_editor_version", 0))
    )

    # ------------------------------------------------------
    # Get the change information generated by st.data_editor
    # ------------------------------------------------------
    editor_state = st.session_state.get(widget_key)

    if not isinstance(editor_state, dict):
        return

    # ------------------------------------------------------
    # Get current AI table
    # ------------------------------------------------------
    edited = st.session_state.get("ai_editor_data")

    if edited is None:
        return

    if not isinstance(edited, pd.DataFrame):
        return

    edited = edited.copy()

    # ------------------------------------------------------
    # Get original AI suggestions
    # ------------------------------------------------------
    original = st.session_state.get("ai_original_suggestions")

    if original is None:
        return

    if not isinstance(original, pd.DataFrame):
        return

    original = original.copy()

    # ------------------------------------------------------
    # Apply only cells changed by the user
    # ------------------------------------------------------
    edited_rows = editor_state.get("edited_rows", {})

    changed_rows = set()

    for row_index, changes in edited_rows.items():

        try:
            row_index = int(row_index)
        except Exception:
            continue

        if row_index < 0 or row_index >= len(edited):
            continue

        if not isinstance(changes, dict):
            continue

        changed_rows.add(row_index)

        for column, value in changes.items():

            if column in edited.columns:
                edited.at[row_index, column] = value

    # ------------------------------------------------------
    # Update status ONLY for rows changed in this edit
    # ------------------------------------------------------
    for index in changed_rows:

        if index >= len(original):
            continue

        original_predecessor = str(
            original.loc[index, "Suggested Predecessor"]
        ).strip()

        original_relationship = str(
            original.loc[index, "Relationship"]
        ).strip()

        current_predecessor = str(
            edited.loc[index, "Suggested Predecessor"]
        ).strip()

        current_relationship = str(
            edited.loc[index, "Relationship"]
        ).strip()

        original_status = str(
            original.loc[index, "Status"]
        ).strip()

        # --------------------------------------------------
        # Existing manually defined relationship
        # --------------------------------------------------
        if original_status == "📌 Existing":

            edited.loc[index, "Status"] = "📌 Existing"

            continue

        # --------------------------------------------------
        # Relationship/predecessor changed
        # --------------------------------------------------
        if (
            current_predecessor != original_predecessor
            or current_relationship != original_relationship
        ):

            edited.loc[index, "Status"] = "✏️ Modified"

            if "Approve" in edited.columns:
                edited.loc[index, "Approve"] = False

        # --------------------------------------------------
        # Approval checkbox changed
        # --------------------------------------------------
        elif (
            "Approve" in edited.columns
            and bool(edited.loc[index, "Approve"])
        ):

            edited.loc[index, "Status"] = "✅ Approved"

        else:

            edited.loc[index, "Status"] = "⏳ Pending"

    # ------------------------------------------------------
    # Save updated data
    # ------------------------------------------------------

    st.session_state.ai_editor_data = edited.copy()

    # ------------------------------------------------------
    # Any new edit invalidates the previous saved review
    # ------------------------------------------------------

    if changed_rows:

        st.session_state.ai_relationship_saved = False

        st.session_state.ai_validation_passed = False

        st.session_state.pop(
            "ai_saved_relationships",
            None
        )

        st.session_state.pop(
            "ai_saved_review",
            None
        )

        # Any relationship edit makes the existing
        # proposed schedule stale.

        st.session_state.pop(
            "proposed_schedule",
            None
        )

        st.session_state.pop(
            "schedule_warnings",
            None
        )

    # ------------------------------------------------------
    # IMPORTANT:
    # DO NOT increment ai_editor_version here.
    # ------------------------------------------------------
    # Incrementing it destroys and recreates the data editor,
    # which causes:
    # - table refresh
    # - scroll reset
    # - fullscreen exit
    # - table resizing
    # ------------------------------------------------------

