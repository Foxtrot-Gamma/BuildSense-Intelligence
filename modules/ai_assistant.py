def convert_ai_relationships_to_activity_data(
    activities,
    reviewed_data
):
    """
    Convert the user-facing activity names in the AI table
    into internal Activity IDs.

    This function does NOT modify session_state.activities.
    It returns a new DataFrame.

    The actual Activity Register is intentionally left
    unchanged until the scheduling workflow decides to
    apply the reviewed relationships.
    """

    updated = activities.copy()

    name_to_ids = {}

    for _, row in activities.iterrows():

        activity_id = str(
            row["ID"]
        ).strip()

        activity_name = str(
            row["Activity"]
        ).strip()

        if activity_name not in name_to_ids:

            name_to_ids[activity_name] = []

        name_to_ids[activity_name].append(
            activity_id
        )

    errors = []

    for index in reviewed_data.index:

        row = reviewed_data.loc[index]

        predecessor_name = str(
            row["Suggested Predecessor"]
        ).strip()

        relationship = str(
            row["Relationship"]
        ).strip()

        # ----------------------------------------------
        # No predecessor
        # ----------------------------------------------

        if (
            not predecessor_name
            or predecessor_name == "None 🔍"
        ):

            updated.at[
                index,
                "Predecessor"
            ] = ""

            updated.at[
                index,
                "Relationship"
            ] = "No Predecessor"

            continue

        # ----------------------------------------------
        # Find internal Activity ID
        # ----------------------------------------------

        matching_ids = name_to_ids.get(
            predecessor_name,
            []
        )

        if len(matching_ids) == 0:

            errors.append(
                f"Unable to find activity: "
                f"{predecessor_name}"
            )

            continue

        if len(matching_ids) > 1:

            errors.append(
                f"Duplicate activity name detected: "
                f"{predecessor_name}"
            )

            continue

        updated.at[
            index,
            "Predecessor"
        ] = matching_ids[0]

        updated.at[
            index,
            "Relationship"
        ] = relationship

    return updated, errors

